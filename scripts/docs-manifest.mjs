// SDK docs sometimes cite a pre-split monolith by its old root filename
// ("API-REFERENCE.md § Initialize the Runtime") even though the href next to
// it points at the specific split sub-page that now owns that section — the
// filename in the prose is a stable "see the reference doc" convention, not
// the actual link target. Keyed by every generated entry's own source
// basename so link-text retitling can still recognize and fix these.
export const basenameIndex = new Map(
  manifest.filter((e) => e.source).map((e) => [e.source.split('/').pop(), e])
);
